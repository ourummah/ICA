/**
 * Compiles contracts/ICAAnchor.sol with the pinned solc and writes the ABI and bytecode to
 * src/lib/anchor/contract-artifact.ts. Run after changing the contract:
 *   node scripts/compile-anchor-contract.ts
 * A unit test recompiles and checks the committed artifact still matches.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { compileAnchorContract } from "./lib/solc.ts";

const out = compileAnchorContract();
const file = path.resolve(import.meta.dirname, "../src/lib/anchor/contract-artifact.ts");
writeFileSync(
  file,
  `// Generated by scripts/compile-anchor-contract.ts from contracts/ICAAnchor.sol. Do not edit.
export const ANCHOR_CONTRACT = ${JSON.stringify(out, null, 2)} as const;
`,
);
console.log(`Wrote ${file} (solc ${out.compiler.version})`);
